package com.example.e2e.support;

import com.example.e2e.config.Config;
import com.example.e2e.config.ConfigKeys;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Properties;

/**
 * Writes the "Environment" widget data and failure categories into the Allure results directory.
 * Allure only reads these files from the results directory, so they're written once per run.
 */
public final class AllureEnvironmentWriter {

    private static final Logger LOG = LoggerFactory.getLogger(AllureEnvironmentWriter.class);

    private AllureEnvironmentWriter() {
    }

    public static void write(Config config) {
        Path resultsDir = Path.of(System.getProperty("allure.results.directory", "build/allure-results"));

        Properties env = new Properties();
        env.setProperty("Environment", config.env());
        env.setProperty("Base URL", config.baseUrl());
        env.setProperty("API base URL", config.apiBaseUrl());
        env.setProperty("Browser", config.get(ConfigKeys.BROWSER));
        env.setProperty("Headless", String.valueOf(config.headless()));
        env.setProperty("Execution", config.remote() ? "remote (" + config.get(ConfigKeys.GRID_URL) + ")" : "local");
        env.setProperty("Threads", String.valueOf(config.threads()));
        env.setProperty("Screenshot mode", config.screenshotMode().name());
        env.setProperty("OS", System.getProperty("os.name") + " " + System.getProperty("os.version"));
        env.setProperty("Java", System.getProperty("java.version"));

        try {
            Files.createDirectories(resultsDir);
            try (OutputStream out = Files.newOutputStream(resultsDir.resolve("environment.properties"))) {
                env.store(out, "Generated by AllureEnvironmentWriter");
            }
            try (InputStream categories = AllureEnvironmentWriter.class.getResourceAsStream("/categories.json")) {
                if (categories != null) {
                    Files.copy(categories, resultsDir.resolve("categories.json"), StandardCopyOption.REPLACE_EXISTING);
                }
            }
            LOG.info("Allure results directory: {}", resultsDir.toAbsolutePath());
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write Allure environment files to " + resultsDir, e);
        }
    }
}
